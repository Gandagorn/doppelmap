SAME_PERSON = 0.35    # ArcFace same-identity floor
MIN_CONSENSUS = 0.5   # below this the gallery is majority-junk -> refuse

names, vecs, n_used, report = [], [], [], []
for name, g in sel.groupby("name"):
    ids = [i for i in g.index if i in img_emb]
    if len(ids) < 3:
        report.append((name, "too few embeddings", len(ids))); continue
    X = np.stack([img_emb[i] for i in ids])
    Ssim = X @ X.T
    medoid = Ssim.sum(1).argmax()              # most "typical" image = the person
    keep = Ssim[medoid] > SAME_PERSON
    if keep.mean() < MIN_CONSENSUS:
        report.append((name, "gallery contaminated", f"{keep.mean():.0%}")); continue
    v = X[keep].mean(0); v /= np.linalg.norm(v)
    names.append(name); vecs.append(v); n_used.append(int(keep.sum()))
E = np.stack(vecs)
