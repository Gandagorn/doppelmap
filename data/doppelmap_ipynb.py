def process(i, img, gender, why):
    """Everything after decode: detect, pick center face, filter, embed."""
    if img is None:
        why["unreadable"] += 1; return
    faces = app.get(img)
    if not faces:
        why["no_face"] += 1; return
    h, w = img.shape[:2]
    f = min(faces, key=lambda f: ((f.bbox[0] + f.bbox[2]) / 2 - w / 2) ** 2
                               + ((f.bbox[1] + f.bbox[3]) / 2 - h / 2) ** 2)
    if f.det_score < 0.6:
        why["low_det"] += 1; return
    if isinstance(gender, str) and ("female" if f.sex == "F" else "male") != gender:
        why["gender_mismatch"] += 1; return
    img_emb[i] = f.normed_embedding.astype(np.float32)
    why["ok"] += 1

